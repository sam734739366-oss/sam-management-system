    let kind = doc ? doc.kind : (KIND_STYLE[presetKind] ? presetKind : null);
    /* a NEW document asks its kind FIRST: the picker is a page of its own,
       and the editor that opens below wears the colour of the chosen kind */
    if (!kind) {
      kind = await openKindPicker(null);
      if (!kind) return null;
    }

    const box = el('div', 'modal editor');
    const ov = el('div', 'overlay');
    ov.appendChild(box);

    const head = el('div', 'ed-head');
