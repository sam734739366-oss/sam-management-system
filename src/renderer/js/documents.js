  /** The launcher of the operations screen — one tile per document kind.
      Every tile wears the colour of its own kind and opens THAT kind's own
      page: no shared grey editor, no grid of ten cards inside the form. */
  function renderKindLauncher() {
    const host = document.getElementById('docKinds');
    if (!host) return;
    host.innerHTML = '';
    Object.entries(KIND_STYLE).forEach(([val, st]) => {
      const tile = el('button', `kl-tile tone-${st.tone}`);
      tile.type = 'button';
      tile.dataset.kind = val;
      tile.title = st.hint;
      const n = state.kindCounts[val] || 0;
      tile.innerHTML = `
        <span class="kc-ic t3d">${SamUI.icon(st.icon)}</span>
        <span class="kl-name">${esc(st.ar)}</span>
        <span class="kl-count">${SamDB.fmt(n)}</span>`;
      tile.addEventListener('click', () => openEditor(null, val));
      host.appendChild(tile);
    });
  }

