  /** The chooser — a popup of coloured cards. It stands on its own so the
      editor that opens below wears the colour of the chosen kind with no
      trace of the other nine. Every document kind is its own page. */
  function openKindPicker(current) {
    return new Promise((resolve) => {
      const ov = el('div', 'overlay');
      const box = el('div', 'modal picker');

      const head = el('div', 'pk-head');
      head.innerHTML = `
        <span class="pk-ic t3d">${SamUI.icon('i-clipboard')}</span>
        <div class="pk-txt">
          <h3>اختر نوع المستند</h3>
          <span class="ed-sub">كل نوع له صفحته المنبثقة ولونه الخاص — اضغط على النوع لتفتح صفحته</span>
        </div>`;
      box.appendChild(head);

      const body = el('div', 'pk-body');
      body.appendChild(kindGridFor((v) => done(v), current));
      box.appendChild(body);

      const foot = el('div', 'modal-foot');
      const cancel = el('button', 'btn btn-ghost', '<span class="btn-txt">إلغاء</span>');
      cancel.type = 'button';
      cancel.addEventListener('click', () => done(null));
      foot.appendChild(cancel);
      box.appendChild(foot);

      ov.appendChild(box);
      document.body.appendChild(ov);

      let settled = false;
      function done(val) {
        if (settled) return;
        settled = true;
        document.removeEventListener('keydown', onKey, true);
        ov.remove();
        resolve(val);
      }
      function onKey(e) { if (e.key === 'Escape') done(null); }
      document.addEventListener('keydown', onKey, true);
      ov.addEventListener('mousedown', (e) => { if (e.target === ov) done(null); });
    });
  }

